"""產生新專案（pipeline/new-project.sh 的實作）。

用法：python3 -I new_project.py <專案名> --platform <平台> --company-role <角色> --os-responsibility <歸屬>
        [--product-name …] [--brand …] [--status development|shipped] [--version v0.1.0-dev1]
        [--markets DE,FR,…|EU-ALL|UNKNOWN] [--support-until YYYY-MM-DD] [--os-distro debian --os-release 13] [--projects-dir <資料夾>]
檔案取自 templates/project/；欄位預設值取自 pipeline/platforms/<平台>/platform.yml 的 project_defaults；
CRA/Config/config.json 只帶必填欄位與 project.yml 的值（產品名稱、支援期限），其他不帶；vex-rules.json 是空規則（D-055：不帶範本值）；
inputs.json 由平台預設值帶入。不覆寫已存在的專案。
"""
import argparse
import json
import os
import re
import shutil
import string
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import project_config as pc  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
TODO = pc.PLACEHOLDER


def _j(v):
    return json.dumps(v, ensure_ascii=False)  # JSON 字串也是合法的 YAML 值


def build_values(args, cfg):
    d = cfg.get("project_defaults") or {}
    s = lambda k: d.get(k, TODO)  # noqa: E731
    return {
        "product_name": _j(args.product_name or args.name), "brand": _j(args.brand or TODO),
        "company_role": _j(args.company_role), "markets": _j([m for m in args.markets.split(",") if m]),
        "platform": _j(args.platform), "platform_version": _j(s("platform_version")),
        "bsp_os_source": _j(s("bsp_os_source")), "kernel_source": _j(s("kernel_source")), "bootloader": _j(s("bootloader")),
        "own_software": _j(d.get("own_software", [])), "interfaces": _j(d.get("interfaces", [TODO])),
        "support_until": _j(args.support_until), "status": _j(args.status), "os_responsibility": _j(args.os_responsibility),
        "version": args.version, "platform_params": _j(d.get("platform_params", {})), "os_block": _os_block(args),
    }


def _os_block(args):
    """os_responsibility 是 ours 才寫 os:（沒給就 TO BE COMPLETED）；其他歸屬省略。"""
    if args.os_responsibility != "ours":
        return ""
    return "os:                                   # 我們自己的 OS：distro 是 /etc/os-release 的 ID（小寫）、release 是 VERSION_ID（字串）\n  distro: %s\n  release: %s\n" % (
        _j(args.os_distro or TODO), _j(args.os_release or TODO))


def _config_json(args, cfg_out):
    """只帶 tools/cra/config.schema.json 的必填欄位，加上 project.yml 已有的值；其餘不寫（報告會標 TO BE COMPLETED）。
    不複製 config.example.json：它的值是範例專案的，會被當成真的。"""
    doc = {
        "$comment": "Generated by new-project.sh. Only the required fields and the values taken from project.yml are set; "
                    "fill the rest (tools/cra/config.example.json shows the structure, but do not copy its values). "
                    "product.name and support.end_date follow project.yml (product_name, support_until).",
        "schema_version": 1,
        "manufacturer": {"name": args.brand or TODO},
        "product": {"name": args.product_name or args.name},
    }
    if re.match(r"^\d{4}-\d{2}-\d{2}$", args.support_until or ""):
        doc["support"] = {"end_date": args.support_until[:7]}      # YYYY-MM；沒填就不寫，schema 的 pattern 不收 TO BE COMPLETED
    with open(cfg_out, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=2)
        fh.write("\n")


def create(args, platforms_dir=pc.PLATFORMS_DIR):
    if not pc.PROJECT_RE.match(args.name):
        raise pc.ConfigError("專案名只能用小寫英數與連字號（最長 63 字元）")
    if not pc.VERSION_RE.match(args.version):
        raise pc.ConfigError("版本必須以 v 加數字開頭，只能用英數與 . _ + -")
    for v, allowed, label in ((args.company_role, pc.COMPANY_ROLES, "company-role"), (args.status, pc.STATUSES, "status"),
                              (args.os_responsibility, pc.OS_RESPONSIBILITIES, "os-responsibility")):
        if v not in allowed:
            raise pc.ConfigError("--%s 必須是 %s" % (label, "／".join(allowed)))
    markets = [m for m in args.markets.split(",") if m]
    if pc.MARKET_LEGACY_EU in markets:
        raise pc.ConfigError("--markets 的 EU 是舊值，請用 EU-ALL（全歐盟）或列出會員國代碼")
    if (args.os_distro or args.os_release) and args.os_responsibility != "ours":
        raise pc.ConfigError("--os-distro／--os-release 只在 --os-responsibility ours 時使用")
    if not pc.PLATFORM_RE.match(args.platform) or not os.path.isfile(os.path.join(platforms_dir, args.platform, "platform.yml")):
        raise pc.ConfigError("未知平台")
    cfg = pc.load_platform_config(args.platform, platforms_dir)
    dest = os.path.join(args.projects_dir, args.name)
    if os.path.lexists(dest):
        raise pc.ConfigError("專案 %s 已存在（不覆寫）" % args.name)
    os.makedirs(args.projects_dir, exist_ok=True)
    tmp = dest + ".tmp-new"
    if os.path.lexists(tmp):
        shutil.rmtree(tmp)
    tpl = os.path.join(ROOT, "templates", "project")
    values = build_values(args, cfg)
    try:
        shutil.copytree(os.path.join(tpl, "patches"), os.path.join(tmp, "patches"))
        for f in ("project.yml", "sources.yml"):
            with open(os.path.join(tpl, f), encoding="utf-8") as fh:
                text = string.Template(fh.read()).substitute(values)
            with open(os.path.join(tmp, f), "w", encoding="utf-8") as fh:
                fh.write(text)
        cdir = os.path.join(tmp, "CRA", "Config")
        os.makedirs(cdir)
        scan = cfg.get("scan") or {}
        _config_json(args, os.path.join(cdir, "config.json"))
        with open(os.path.join(cdir, "vex-rules.json"), "w", encoding="utf-8") as fh:   # 空規則：範例規則的作者、日期、映像雜湊都是範例值
            json.dump({"schema": "sca-center-vex-rules/1", "rules": []}, fh, indent=1)
            fh.write("\n")
        inputs = os.path.join(ROOT, "tools", "wizard", "platforms", "%s.json" % scan.get("inputs_template", args.platform))
        if os.path.isfile(inputs):
            shutil.copyfile(inputs, os.path.join(cdir, "inputs.json"))
        else:  # 平台沒有精靈的輸入清單範本：留空清單檔，掃描時不檢查必要輸入
            with open(os.path.join(cdir, "inputs.json"), "w", encoding="utf-8") as fh:
                fh.write(json.dumps({"schema": 1, "platform": args.platform, "draft": True, "inputs": []}, indent=1) + "\n")
        pc.load_project_all(tmp, platforms_dir)  # 產生的專案一定要通過驗證
        os.rename(tmp, dest)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    return dest


def main(argv=None):
    ap = argparse.ArgumentParser(prog="new-project.sh")
    ap.add_argument("name")
    ap.add_argument("--platform", required=True)
    ap.add_argument("--company-role", required=True)
    ap.add_argument("--os-responsibility", required=True)
    ap.add_argument("--product-name")
    ap.add_argument("--brand")
    ap.add_argument("--status", default="development")
    ap.add_argument("--version", default="v0.1.0-dev1")
    ap.add_argument("--markets", default=TODO)
    ap.add_argument("--support-until", default=TODO)
    ap.add_argument("--os-distro")
    ap.add_argument("--os-release")
    ap.add_argument("--projects-dir", default=os.path.join(ROOT, "projects"))
    try:
        args = ap.parse_args(argv)
    except SystemExit as e:
        return 64 if e.code else 0
    if pc.yaml is None:
        print("new-project: FAIL（缺少 PyYAML）")
        return 1
    try:
        dest = create(args)
    except pc.ConfigError as e:
        print("new-project: FAIL（%s）" % e)
        return 1
    except (OSError, ValueError) as e:
        print("new-project: FAIL（%s）" % type(e).__name__)
        return 1
    print("new-project: OK（%s；請填完 project.yml／sources.yml 的 %s 欄位再推上去）" % (os.path.relpath(dest, ROOT) if dest.startswith(ROOT) else args.name, TODO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
