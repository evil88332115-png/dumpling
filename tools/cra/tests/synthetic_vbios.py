#!/usr/bin/env python3
"""合成的 NVIDIA option ROM（測試用）：legacy x86 影像＋EFI 影像＋NPDE＋`XX.XX.XX.XX.XX` 版本字串＋正確的 checksum。

用途：沒有官方可合法下載的獨立 vBIOS 時（firmware/vbios/standalone-nvidia-option-rom 是 GAP），CI 用它測
「option ROM → x86_firmware.py → CycloneDX」整條流程。**這不是任何真實產品的 vBIOS**：內容是這個檔案自己組的位元組
（沒有任何 NVIDIA 的程式碼或資料），ROM 裡有明確的「SYNTHETIC」字樣，預設裝置 ID 0xFFFE 也不是已配置的 NVIDIA 裝置。
實際檔案由負責單位提供。

用法：
  python3 -I synthetic_vbios.py --out synthetic-nvidia-option-rom.rom [--version 00.00.00.00.01] [--device 0xFFFE] [--no-efi]
  輸出檔名請保留 `synthetic` 字樣：x86_firmware 的 SBOM 會把輸入檔名記在 `bsi:component:filename`／`sca-center:found-in`，
  下游看得到這是合成樣本。

結構（欄位位置同 x86_firmware.pci_image 讀的、也是 PCI Firmware Spec 3.x 與 nouveau shadow.c／npde.c 的做法）：
  影像 0（legacy x86，code type 0，不是最後一個）：
    +0 `55 AA`、+2 長度（512 bytes 為單位）、+3 三個 bytes 的 JMP（`E9 00 00`，只是填位置，沒有程式）、+0x18 PCIR 指標（0x40）。
    +0x40 PCIR（0x18 bytes）：`PCIR`、vendor 0x10DE、device、裝置清單指標 0、長度 0x18、revision 0、class code（3 bytes，
    小端：`00 00 03` ＝ 0x030000 VGA）、影像長度（512 bytes 為單位）、revision level、code type、indicator（bit7＝最後一個）、最長執行時間 0。
    +0x60 NPDE（NVIDIA 延伸，PCIR 結尾 0x58 對齊 16 bytes 之後）：`NPDE`、revision 0x0100、長度 0x10、影像長度（512 bytes 為單位）、
    indicator（bit7＝最後一個）、其餘 0。NPDE 的影像長度與最後一個旗標優先於 PCIR（x86_firmware 的做法）。
    +0x80 起是說明文字（SYNTHETIC 字樣與 `Version <版本>`）。
    最後一個 byte 補 checksum：整個影像加起來 mod 256 ＝ 0（legacy option ROM 的規則）。
  影像 1（EFI，code type 3，最後一個）：
    +0 `55 AA`、+2 初始化大小、+4 EFI 簽章 0x0EF1、+8 subsystem 11、+0xA machine 0x8664、+0xC 壓縮 0、+0x16 EFI 映像偏移、
    +0x18 PCIR 指標（0x1C）；PCIR 在 +0x1C，NPDE 在 +0x40（PCIR 結尾 0x34 對齊 16 bytes）；+0x50 起是填充文字（不是 PE，沒有可執行內容）。
"""
import argparse
import os
import struct
import sys

NVIDIA_VID = 0x10DE
DEFAULT_DEVICE = 0xFFFE                  # 沒有配置給任何 NVIDIA 裝置的 ID
DEFAULT_VERSION = "00.00.00.00.01"
IMAGE_SIZE = 1024                        # 每個影像的大小（2 個 512 bytes 單位）
MARK = b"SYNTHETIC TEST ROM - NOT A REAL NVIDIA PRODUCT - generated by dumpling tools/cra/tests/synthetic_vbios.py"


def pcir(vendor, device, units, code_type, last):
    return (b"PCIR" + struct.pack("<HHHHB", vendor, device, 0, 0x18, 0) + bytes([0x00, 0x00, 0x03])
            + struct.pack("<HHBBH", units, 0, code_type, 0x80 if last else 0, 0))


def npde(units, last):
    return b"NPDE" + struct.pack("<HHHBB", 0x0100, 0x10, units, 0x80 if last else 0, 0) + b"\0" * 4


def legacy_image(device, version, last):
    units = IMAGE_SIZE // 512
    img = bytearray(IMAGE_SIZE)
    img[0:2] = b"\x55\xaa"
    img[2] = units
    img[3:6] = b"\xe9\x00\x00"
    struct.pack_into("<H", img, 0x18, 0x40)
    text = MARK + b"\r\n" + b"Version " + version.encode("ascii") + b"\r\n"
    assert 0x80 + len(text) < IMAGE_SIZE
    img[0x80:0x80 + len(text)] = text
    img[0x40:0x58] = pcir(NVIDIA_VID, device, units, 0, last)
    img[0x60:0x70] = npde(units, last)
    img[-1] = (-sum(img[:-1])) & 0xFF
    assert sum(img) % 256 == 0
    return bytes(img)


def efi_image(device):
    units = IMAGE_SIZE // 512
    img = bytearray(IMAGE_SIZE)
    img[0:2] = b"\x55\xaa"
    struct.pack_into("<HIHHHH", img, 2, units, 0x0EF1, 11, 0x8664, 0, 0)
    struct.pack_into("<HH", img, 0x16, 0x50, 0x1C)
    img[0x1C:0x34] = pcir(NVIDIA_VID, device, units, 3, True)
    img[0x40:0x50] = npde(units, True)
    img[0x50:0x50 + len(MARK)] = MARK
    return bytes(img)


def synthetic_rom(version=DEFAULT_VERSION, device=DEFAULT_DEVICE, efi=True):
    """合成 ROM 的位元組。version 必須是 XX.XX.XX.XX.XX（大寫十六進位）；efi=False 時只有 legacy 影像（標最後一個）。"""
    if len(version) != 14 or any((c != "." if i % 3 == 2 else c not in "0123456789ABCDEF") for i, c in enumerate(version[:14])):
        raise ValueError("version 要是 XX.XX.XX.XX.XX（大寫十六進位）")
    if not 0 <= device <= 0xFFFF:
        raise ValueError("device 要在 0..0xFFFF")
    return legacy_image(device, version, not efi) + (efi_image(device) if efi else b"")


def main(argv=None):
    ap = argparse.ArgumentParser(description="產生合成的 NVIDIA option ROM（測試用，不是真實的 vBIOS）")
    ap.add_argument("--out", required=True)
    ap.add_argument("--version", default=DEFAULT_VERSION)
    ap.add_argument("--device", default=hex(DEFAULT_DEVICE))
    ap.add_argument("--no-efi", action="store_true", help="只產生 legacy 影像")
    a = ap.parse_args(argv)
    try:
        data = synthetic_rom(a.version, int(a.device, 0), not a.no_efi)
    except ValueError as e:
        print(f"synthetic_vbios: {e}", file=sys.stderr)
        return 64
    if os.path.islink(a.out):
        print("synthetic_vbios: --out 是 symlink，拒絕寫入", file=sys.stderr)
        return 1
    with open(a.out, "wb") as f:
        f.write(data)
    print(f"synthetic_vbios: {a.out} {len(data)} bytes（合成樣本，不是真實 vBIOS）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
